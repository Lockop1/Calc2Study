// ── Parameterized generators ───────────────────────────────────────────────────────────────
function mulberry(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** `x^{k}` in LaTeX (plain `x` when k = 1). */
function xPow(k: number): string {
  return k === 1 ? 'x' : `x^{${k}}`;
}

